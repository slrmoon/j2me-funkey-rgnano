    private JapaneseFont() {}

    public static boolean hasJapanese(String s) {
        if (s == null) return false;
        for (int i = 0; i < s.length(); i++) {
            if (s.charAt(i) >= 0x80) return true;
        }
        return false;
    }

    public static int stringWidth(String s, int fallbackWidth) {
        if (s == null || s.length() == 0) return 0;
        int w = 0;
        for (int i = 0; i < s.length(); i++) {
            char ch = s.charAt(i);
            int idx = find(ch);
            if (idx >= 0) w += hex1(ADV_HEX.charAt(idx));
            else w += ch < 0x80 ? fallbackWidth : WIDTH;
        }
        return w;
    }

    public static void drawString(Graphics g, String s, int x, int y) {
        if (s == null) return;
        int cx = x;
        for (int i = 0; i < s.length(); i++) {
            char ch = s.charAt(i);
            int idx = find(ch);
            if (idx >= 0) {
                drawGlyph(g, idx, cx, y);
                cx += hex1(ADV_HEX.charAt(idx));
            } else if (ch < 0x80) {
                g.drawChar(ch, cx, y, Graphics.LEFT | Graphics.TOP);
                cx += javax.microedition.lcdui.Font.getDefaultFont().charWidth(ch);
            } else {
                drawMissing(g, cx, y);
                cx += WIDTH;
            }
        }
    }

    private static void drawGlyph(Graphics g, int idx, int x, int y) {
        int base = idx * HEIGHT * 3;
        for (int row = 0; row < HEIGHT; row++) {
            int pos = base + row * 3;
            int bits = (hex1(ROWS_HEX.charAt(pos)) << 8) | (hex1(ROWS_HEX.charAt(pos + 1)) << 4) | hex1(ROWS_HEX.charAt(pos + 2));
            for (int col = 0; col < WIDTH; col++) {
                if ((bits & (1 << (WIDTH - 1 - col))) != 0) {
                    g.fillRect(x + col, y + row, 1, 1);
                }
            }
        }
    }

    private static void drawMissing(Graphics g, int x, int y) {
        g.drawRect(x + 1, y + 2, WIDTH - 3, HEIGHT - 4);
    }

    private static int find(int code) {
        int lo = 0;
        int hi = CODES_HEX.length() / 4 - 1;
        while (lo <= hi) {
            int mid = (lo + hi) >>> 1;
            int value = hex4(CODES_HEX, mid * 4);
            if (value < code) lo = mid + 1;
            else if (value > code) hi = mid - 1;
            else return mid;
        }
        return -1;
    }

    private static int hex4(String s, int pos) {
        return (hex1(s.charAt(pos)) << 12) | (hex1(s.charAt(pos + 1)) << 8) | (hex1(s.charAt(pos + 2)) << 4) | hex1(s.charAt(pos + 3));
    }

    private static int hex1(char ch) {
        if (ch >= '0' && ch <= '9') return ch - '0';
        if (ch >= 'a' && ch <= 'f') return ch - 'a' + 10;
        return 0;
    }
