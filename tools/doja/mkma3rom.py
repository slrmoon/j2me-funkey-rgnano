#!/usr/bin/env python3
"""Builds fka_ma3_rom.h (fkaudio MA-3 FM synth data) from the Keitai Wiki /
SquirrelJME vendor-api-keitaiwiki-music resources (base64 '*.__mime' files).

usage: mkma3rom.py <resources dir com/keitaiwiki/music> <out.h>
"""
import base64, os, sys

SETS = [('3i40p', 128, 'INST4'), ('3d40p', 61, 'DRUM4'), ('3d', 21, 'WDRUM'), ('3wr', 7, 'WROM')]

def load(d, prefix, i):
    p = os.path.join(d, '%s.%02x.__mime' % (prefix, i))
    lines = open(p).read().split('\n')[1:]
    return base64.b64decode(''.join(l for l in lines if l and l != '===='))

src, out = sys.argv[1], sys.argv[2]
o = ['/* Generated by tools/doja/mkma3rom.py from the Keitai Wiki music',
     ' * resources (SquirrelJME modules/vendor-api-keitaiwiki-music). */',
     '#ifndef FKA_MA3_ROM_H', '#define FKA_MA3_ROM_H', '#include <stdint.h>']
for prefix, count, name in SETS:
    blobs = [load(src, prefix, i) for i in range(count)]
    offs = []
    data = bytearray()
    for b in blobs:
        offs.append(len(data))
        data += b
    offs.append(len(data))
    o.append('#define MA3_%s_COUNT %d' % (name, count))
    o.append('static const uint32_t ma3_%s_off[%d] = {%s};' % (name.lower(), count + 1, ','.join(map(str, offs))))
    o.append('static const uint8_t ma3_%s_data[%d] = {' % (name.lower(), len(data)))
    for i in range(0, len(data), 24):
        o.append('    ' + ','.join(str(x) for x in data[i:i + 24]) + ',')
    o.append('};')
o.append('#endif')
open(out, 'w').write('\n'.join(o) + '\n')
print(out)
