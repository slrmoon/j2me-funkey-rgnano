#!/usr/bin/env python3
"""Generates SJIS_Table.java (Shift-JIS double-byte -> Unicode, cp932 incl.
NEC/IBM extensions; F040-F9FC map to the private use area, which is where
DoCoMo pictograms live, F89F -> U+E63E)."""
import sys
out = []
for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD)):
    for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFD)):
        try:
            c = bytes([lead, trail]).decode('cp932')
            out.append(ord(c) if len(c) == 1 else 0xFFFD)
        except UnicodeDecodeError:
            out.append(0xFFFD)
assert len(out) == 60 * 188
lines = []
for i in range(0, len(out), 16):
    lines.append('        "' + ''.join('\\u%04x' % c for c in out[i:i + 16]) + '"')
src = '''/* Generated by tools/doja/mksjis.py: do not edit. */
package com.sun.cldc.i18n.j2me;

/** Shift-JIS double-byte table: index (lead row) * 188 + trail column. */
final class SJIS_Table {
    static final String MAP =
''' + ' +\n'.join(lines) + ''';

    private SJIS_Table() {
    }

    /** Column of a trail byte, -1 when invalid. */
    static int column(int t) {
        if (t >= 0x40 && t <= 0x7E) return t - 0x40;
        if (t >= 0x80 && t <= 0xFC) return t - 0x41;
        return -1;
    }

    /** Row of a lead byte, -1 when it is not a lead byte. */
    static int row(int b) {
        if (b >= 0x81 && b <= 0x9F) return b - 0x81;
        if (b >= 0xE0 && b <= 0xFC) return b - 0xC1;
        return -1;
    }

    static char decode(int lead, int trail) {
        int r = row(lead), c = column(trail);
        return r < 0 || c < 0 ? '\\ufffd' : MAP.charAt(r * 188 + c);
    }

    private static short[] reverse;

    /** Shift-JIS code of a character (single byte < 0x100), -1 when none. */
    static synchronized int encode(char ch) {
        if (ch < 0x80) return ch;
        if (ch >= 0xFF61 && ch <= 0xFF9F) return ch - 0xFF61 + 0xA1;
        if (reverse == null) {
            short[] t = new short[65536];
            for (int i = MAP.length() - 1; i >= 0; i--) {
                char u = MAP.charAt(i);
                if (u != '\\ufffd') {
                    int r = i / 188, c = i % 188;
                    int lead = r < 31 ? r + 0x81 : r + 0xC1;
                    int trail = c < 63 ? c + 0x40 : c + 0x41;
                    t[u] = (short) (lead << 8 | trail);
                }
            }
            reverse = t;
        }
        int v = reverse[ch] & 0xFFFF;
        return v == 0 ? -1 : v;
    }
}
'''
open(sys.argv[1], 'w').write(src)
